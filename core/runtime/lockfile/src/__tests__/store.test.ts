import { describe, it, expect, beforeEach } from 'vitest'
import { mkdtemp, rm, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { LockfileStoreImpl } from '../store.js'
import { LockfileGeneratorImpl } from '../generator.js'
import type { DeliveredEnvironmentSnapshot, LockfileAuditMetadata } from '@rohinik-org/lockfile-ir'

const AUDIT: LockfileAuditMetadata = {
  generatedAt: '2026-01-01T00:00:00Z',
  generatedBy: { implementationId: 'rohinik-lockfile', version: '0.1.0' },
  provisioningExecutionId: 'exec-1',
  provisioningSemanticJournalHash: 'sjh',
}

function makeSnapshot(): DeliveredEnvironmentSnapshot {
  return {
    kind: 'delivered-environment-snapshot',
    snapshotVersion: 1,
    application: { applicationId: 'app1', manifestSemanticHash: 'msh', manifestSchemaVersion: 1 },
    runtime: { os: 'linux', architecture: 'x64', runtimeKind: 'nodejs', runtimeVersion: '20.0.0' },
    resolution: {
      proposedPlanId: 'plan1',
      proposedPlanSemanticHash: 'psh',
      authorizedPlanSemanticHash: 'apsh',
      authorizationId: 'auth1',
      resolverIdentity: { implementationId: 'res', version: '1.0.0' },
      resolutionPolicySemanticHash: 'rpsh',
      catalogSnapshots: [],
    },
    capabilities: [],
    packages: [],
    dependencies: {},
    models: [],
    infrastructure: [],
    providers: [],
    configuration: [],
    policies: {
      trustPolicySemanticHash: 'tsh',
      permissionPolicySemanticHash: 'ppsh',
      authorizationPolicySemanticHash: 'ash',
    },
    provisioningEvidence: {
      executionId: 'exec-1',
      status: 'success',
      semanticJournalHash: 'sjh',
    },
  }
}

const store = new LockfileStoreImpl()
const generator = new LockfileGeneratorImpl()

let tmpDir: string

beforeEach(async () => {
  tmpDir = await mkdtemp(join(tmpdir(), 'lockfile-test-'))
})

describe('LockfileStoreImpl', () => {
  it('writeAtomic creates rohinik.lock', async () => {
    const lockfile = generator.generate(makeSnapshot(), AUDIT)
    await store.writeAtomic(tmpDir, lockfile)
    const content = await readFile(join(tmpDir, 'rohinik.lock'), 'utf8')
    expect(content).toContain('rohinik-lockfile')
    expect(content).toContain('Generated by Rohinik')
  })

  it('readRaw reads file content', async () => {
    const lockfile = generator.generate(makeSnapshot(), AUDIT)
    await store.writeAtomic(tmpDir, lockfile)
    const raw = await store.readRaw(tmpDir)
    expect(raw).toBeDefined()
    expect(raw).toContain('rohinik-lockfile')
  })

  it('read parses a valid lockfile', async () => {
    const lockfile = generator.generate(makeSnapshot(), AUDIT)
    await store.writeAtomic(tmpDir, lockfile)
    const parsed = await store.read(tmpDir)
    expect(parsed).toBeDefined()
    expect(parsed!.kind).toBe('rohinik-lockfile')
    expect(parsed!.semanticHash).toBe(lockfile.semanticHash)
  })

  it('read returns undefined for missing lockfile', async () => {
    const result = await store.read(tmpDir)
    expect(result).toBeUndefined()
  })

  it('readRaw returns undefined for missing file', async () => {
    const result = await store.readRaw(tmpDir)
    expect(result).toBeUndefined()
  })

  it('writeAtomic replaces existing file when called twice', async () => {
    // Write a valid file first
    const lockfile1 = generator.generate(makeSnapshot(), AUDIT)
    await store.writeAtomic(tmpDir, lockfile1)
    const originalContent = await readFile(join(tmpDir, 'rohinik.lock'), 'utf8')

    // Write a second valid lockfile
    const lockfile2 = generator.generate({
      ...makeSnapshot(),
      application: { applicationId: 'app2', manifestSemanticHash: 'msh2', manifestSchemaVersion: 1 },
    }, { ...AUDIT, generatedAt: '2026-07-01T00:00:00Z' })
    await store.writeAtomic(tmpDir, lockfile2)
    const newContent = await readFile(join(tmpDir, 'rohinik.lock'), 'utf8')

    // The file changed to the new lockfile — this verifies atomic write replaced correctly.
    expect(newContent).not.toBe(originalContent)
    expect(newContent).toContain('app2')
  })

  it('writeAtomic failure leaves previous file unchanged', async () => {
    // Write a valid file first
    const lockfile1 = generator.generate(makeSnapshot(), AUDIT)
    await store.writeAtomic(tmpDir, lockfile1)
    const originalContent = await readFile(join(tmpDir, 'rohinik.lock'), 'utf8')

    // Attempt write to a non-existent subdirectory — should fail
    const badDir = join(tmpDir, 'no-such-sub', 'nested')
    const lockfile2 = generator.generate({
      ...makeSnapshot(),
      application: { applicationId: 'app3', manifestSemanticHash: 'msh3', manifestSchemaVersion: 1 },
    }, AUDIT)
    await expect(store.writeAtomic(badDir, lockfile2)).rejects.toThrow()

    // Original file must still be intact
    const afterContent = await readFile(join(tmpDir, 'rohinik.lock'), 'utf8')
    expect(afterContent).toBe(originalContent)
  })

  it('tmp file cleaned up on write error', async () => {
    // Write to a non-existent directory to trigger failure
    const nonExistentDir = join(tmpDir, 'no-such-dir')
    const lockfile = generator.generate(makeSnapshot(), AUDIT)
    await expect(store.writeAtomic(nonExistentDir, lockfile)).rejects.toThrow()
    // Verify no tmp file left in tmpDir itself
    const files = await readFile(join(tmpDir, 'rohinik.lock.rhk-tmp'), 'utf8').catch(() => null)
    expect(files).toBeNull()
  })
})
